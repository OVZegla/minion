const LAST_KEY = 'minion:lastPhrase'

/** Tire une phrase au hasard, sans répéter celle de la dernière ouverture. */
export function randomPhrase(extra: string[] = []): string {
  const pool = [...PHRASES, ...extra]
  let last = -1
  try {
    last = Number(localStorage.getItem(LAST_KEY) ?? -1)
  } catch {
    /* stockage indisponible */
  }
  let i = Math.floor(Math.random() * pool.length)
  if (pool.length > 1 && i === last) i = (i + 1 + Math.floor(Math.random() * (pool.length - 1))) % pool.length
  try {
    localStorage.setItem(LAST_KEY, String(i))
  } catch {
    /* stockage indisponible */
  }
  return pool[i]
}

/** « Bonjour » de 5 h à 18 h, « Bonsoir » sinon. */
export function greeting(date = new Date()): 'Bonjour' | 'Bonsoir' {
  const h = date.getHours()
  return h >= 5 && h < 18 ? 'Bonjour' : 'Bonsoir'
}

/** « de Léa » / « d’Einat » : élision devant une voyelle ou un h muet. */
export function deName(name: string) {
  return /^[aeiouyhàâäéèêëîïôöùûü]/i.test(name.trim()) ? `d’${name}` : `de ${name}`
}

/** Seulement la préposition : « de » ou « d’ ». */
export function deWord(name: string) {
  return deName(name).startsWith('d’') ? 'd’' : 'de'
}
